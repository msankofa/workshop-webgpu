// Writes docs/vehicle-parts.md: every craft kind, every named part, its size and where it sits.
// Derived from the builders in authoring mode, so it cannot drift from the code the way a
// hand-written parts list would. Run after changing any builder: node bake-vehicle-parts.mjs
import fs from 'node:fs';
import * as THREE from 'three';
import { buildCraftMesh, setMeshAuthoring, CRAFT_KINDS } from './flight-meshes.js';
import { BASE_GAME_VEHICLE_DEFS } from './base-game-vehicles.js';

const MATS = {
  standard: (c, e = 0) => new THREE.MeshStandardMaterial({ color: c, emissive: e }),
  basic: (c, o = 1) => new THREE.MeshBasicMaterial({ color: c, opacity: o }),
};

export function vehicleParts(kind) {
  setMeshAuthoring(true);
  let g;
  try { g = buildCraftMesh(kind, 0x808080, MATS, BASE_GAME_VEHICLE_DEFS[kind]); }
  finally { setMeshAuthoring(false); }
  g.updateMatrixWorld(true);
  const parts = [];
  const box = new THREE.Box3(), size = new THREE.Vector3(), mid = new THREE.Vector3();
  g.traverse((o) => {
    if (!o.geometry) return;
    box.setFromObject(o); box.getSize(size); box.getCenter(mid);
    const ix = o.geometry.index, pos = o.geometry.attributes.position;
    parts.push({
      name: o.name || '(unnamed)',
      tris: Math.round((ix ? ix.count : pos.count) / 3),
      size: [size.x, size.y, size.z].map(v => +v.toFixed(3)),
      at: [mid.x, mid.y, mid.z].map(v => +v.toFixed(3)),
    });
  });
  parts.sort((a, b) => a.name.localeCompare(b.name));
  return parts;
}

function render() {
  const out = ['# Vehicle parts', '',
    'Generated by `bake-vehicle-parts.mjs` — do not edit by hand. One row per mesh in a build with',
    '`setMeshAuthoring(true)`, which skips the per-material merge the runtime uses. These are the',
    'names a model exported for Blender carries, and the names to use when reading an edit back in.',
    '', '`size` and `at` are metres in the mesh frame: nose at -Z, ground at y = -clearance.', ''];
  for (const kind of CRAFT_KINDS) {
    const parts = vehicleParts(kind);
    const tris = parts.reduce((t, p) => t + p.tris, 0);
    out.push(`## ${kind}`, '', `${parts.length} parts, ${tris} triangles.`, '',
      '| part | tris | size w,h,l | centre x,y,z |', '|---|---|---|---|');
    for (const p of parts) {
      out.push(`| \`${p.name}\` | ${p.tris} | ${p.size.join(' ')} | ${p.at.join(' ')} |`);
    }
    out.push('');
  }
  return out.join('\n');
}

// Run directly to rewrite the doc; imported by the test, which only wants `vehicleParts`.
if (process.argv[1] && process.argv[1].endsWith('bake-vehicle-parts.mjs')) {
  fs.writeFileSync('docs/vehicle-parts.md', render());
  console.log('wrote docs/vehicle-parts.md');
}

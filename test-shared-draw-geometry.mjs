import assert from 'node:assert/strict';
import * as THREE from 'three';
import Geometries from './node_modules/three/src/renderers/common/Geometries.js';
import { createSharedDrawGeometryPool } from './shared-draw-geometry.js';

const deleted = [];
const attributes = { delete(attribute) { deleted.push(attribute); } };
const originalDelete = attributes.delete;
const info = { memory: { geometries: 0 } };
const geometries = new Geometries(attributes, info);
const pool = createSharedDrawGeometryPool({ _attributes: attributes });
const source = new THREE.BoxGeometry();
const otherSource = new THREE.BoxGeometry(2, 2, 2);
const a = pool.acquire(source, 12, { id: 'a' }), b = pool.acquire(source, 12, { id: 'b' });
assert.notEqual(a, b); assert.notEqual(a.indirect, b.indirect);
assert.equal(a.attributes.position, b.attributes.position);
assert.equal(a.index, b.index);
assert.notEqual(a.attributes.position, source.attributes.position, 'palette ownership stays independent');
assert.deepEqual(a.attributes.position.array, source.attributes.position.array);
assert.deepEqual(a.index.array, source.index.array);
assert.deepEqual(a.groups, source.groups);
assert.equal(a.instanceCount, 12);
const renderA = { geometry: a, getAttributes() { return Object.values(this.geometry.attributes); } };
const renderB = { geometry: b, getAttributes() { return Object.values(this.geometry.attributes); } };
geometries.initGeometry(renderA); geometries.initGeometry(renderB);
pool.release(a);
assert.equal(deleted.length, 0, 'real Three disposal must not destroy attributes of a live sibling');
assert.equal(info.memory.geometries, 1, 'the retired render wrapper is disposed immediately');
assert.equal(attributes.delete, originalDelete, 'the renderer method is restored');
const replacement = pool.acquire(otherSource, 12, { id: 'replacement' });
renderA.geometry = replacement;
geometries.initGeometry(renderA);
pool.release(b);
assert.ok(deleted.includes(b.index)); assert.ok(deleted.includes(b.attributes.position));
assert.ok(!deleted.includes(replacement.attributes.position), 'replacement attributes survive the old owner retirement');
assert.equal(pool.sourceCount, 1);
pool.release(replacement);
assert.equal(pool.sourceCount, 0); assert.equal(info.memory.geometries, 0);
const count = deleted.length;
pool.release(replacement);
assert.equal(deleted.length, count, 'release is idempotent');
const failing = pool.acquire(source, 1, null);
failing.addEventListener('dispose', () => { throw new Error('listener failure'); });
assert.throws(() => pool.release(failing), /listener failure/);
assert.equal(attributes.delete, originalDelete, 'failure restores the renderer method too');
assert.equal(pool.sourceCount, 0);
source.dispose(); otherSource.dispose();
console.log('shared draw geometry: identical data, independent draws, real Three disposal, replacement, and failure checks passed');
